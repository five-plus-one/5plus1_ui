import fs from "node:fs";
import ts from "typescript";
const source = ts.createSourceFile(
  "catalog.tsx",
  fs.readFileSync("src/catalog.tsx", "utf8"),
  ts.ScriptTarget.Latest,
  true,
  ts.ScriptKind.TSX,
);
const fn = source.statements.find(
  (n) => ts.isFunctionDeclaration(n) && n.name?.text === "Demo",
);
const decls = fn.body.statements
  .filter(ts.isVariableStatement)
  .flatMap((s) => [...s.declarationList.declarations]);
const demos = decls.find(
  (d) => d.name.getText(source) === "examples",
).initializer;
function ids(node) {
  const out = new Set();
  function visit(n) {
    if (
      ts.isIdentifier(n) &&
      !(ts.isPropertyAssignment(n.parent) && n.parent.name === n) &&
      !(ts.isPropertyAccessExpression(n.parent) && n.parent.name === n) &&
      !ts.isJsxAttribute(n.parent)
    )
      out.add(n.text);
    ts.forEachChild(n, visit);
  }
  visit(node);
  return out;
}
const records = decls
  .filter((d) => d.name.getText(source) !== "examples")
  .map((d) => ({
    names: ids(d.name),
    uses: ids(d.initializer),
    code: `const ${d.getText(source)};`,
  }));
const icons = source.statements
  .find(
    (n) =>
      ts.isImportDeclaration(n) && n.moduleSpecifier.text === "lucide-react",
  )
  .getText(source);
const examples = {};
for (const p of demos.properties) {
  if (!ts.isPropertyAssignment(p) || !ts.isArrowFunction(p.initializer))
    continue;
  const body = p.initializer.body.getText(source);
  if (
    /<(ResourceExplorerDemo|ChatComposerDemo|MarkdownEditorDemo|WorkspaceLayoutDemo|ShareAccessDemo|UploadQueueDemo)/.test(
      body,
    )
  )
    continue;
  const needed = ids(p.initializer.body),
    selected = new Set();
  let changed = true;
  while (changed) {
    changed = false;
    records.forEach((r, i) => {
      if (!selected.has(i) && [...r.names].some((id) => needed.has(id))) {
        selected.add(i);
        r.uses.forEach((id) => needed.add(id));
        changed = true;
      }
    });
  }
  examples[p.name.getText(source)] =
    `import React, {useState} from 'react';\nimport * as U from '@fiveplusone/ui';\n${icons}\nimport '@fiveplusone/ui/styles.css';\nexport function Example(){\n${needed.has("notify") ? "const notify=(message:string)=>console.info(message);\n" : ""}${records
      .filter((r, i) => selected.has(i))
      .map((r) => r.code)
      .join("\n")}\nreturn (${body});\n}`;
}
const manual = ts.createSourceFile(
  "component-code.ts",
  fs.readFileSync("src/component-code.ts", "utf8"),
  ts.ScriptTarget.Latest,
  true,
  ts.ScriptKind.TSX,
);
const manualFn = manual.statements.find(
  (n) => ts.isFunctionDeclaration(n) && n.name?.text === "componentCode",
);
const manualMap = manualFn.body.statements
  .filter(ts.isVariableStatement)
  .flatMap((s) => [...s.declarationList.declarations])
  .find((d) => d.name.getText(manual) === "examples").initializer;
for (const key of [
  "ResourceExplorer",
  "ChatComposer",
  "MarkdownEditor",
  "WorkspaceLayout",
  "UploadQueue",
  "MemberSearch",
  "ShareLink",
]) {
  const p = manualMap.properties.find((p) => p.name.getText(manual) === key);
  if (!p || !ts.isStringLiteral(p.initializer))
    throw Error("Missing example " + key);
  examples[key] =
    `import {useState} from 'react';\nimport {${key}} from '@fiveplusone/ui';\nimport '@fiveplusone/ui/styles.css';\nexport function Example(){\n${[["setText","const [text,setText]=useState('');"],["setFolder","const [folder,setFolder]=useState<string|null>(null);"],["setSelected","const [selected,setSelected]=useState<string[]>([]);"],["setMessage","const [message,setMessage]=useState('');"],["setOpen","const [open,setOpen]=useState(false);"]].filter(([name])=>p.initializer.text.includes(name)).map(([,code])=>code).join("\n")}\nreturn (${p.initializer.text});\n}`;
}
fs.writeFileSync(
  "src/catalog-examples.ts",
  `// Generated by scripts/build-catalog-examples.mjs.\nexport const catalogExamples:Record<string,string>=${JSON.stringify(examples, null, 2)};\n`,
);

console.log(`Prepared ${Object.keys(examples).length} catalog examples.`);
